/// Localized display label for a preference option.
///
/// Preference values are stored (and sent to the backend) as stable English
/// strings or ids; only what the user sees is translated. Unknown values -
/// e.g. a cuisine the user typed - are shown as-is.
String optionLabel(BuildContext context, String value) {
  final label = _labels[value];
  return label == null ? value : label(context.l10n);
}

/// Joins several stored values into one localized, comma-separated label.
String optionLabels(BuildContext context, Iterable<String> values) =>
    values.map((v) => optionLabel(context, v)).join(', ');

